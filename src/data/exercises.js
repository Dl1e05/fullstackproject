// Exercise: id, kind ('practice' — задание к уроку, 'quiz' — вопрос итогового теста),
// lessonId | courseId, question, options: AnswerOption[], correctId, explanation
// AnswerOption: id, text

const LETTERS = ['a', 'b', 'c', 'd'];

function practice(lessonId, question, options, correct, explanation) {
  return make(`ex-${lessonId}`, { kind: 'practice', lessonId }, question, options, correct, explanation);
}
function quiz(courseId, n, question, options, correct, explanation) {
  return make(`q-${courseId}-${n}`, { kind: 'quiz', courseId, order: n }, question, options, correct, explanation);
}
function make(id, extra, question, options, correct, explanation) {
  return {
    id,
    ...extra,
    question,
    options: options.map((text, i) => ({ id: LETTERS[i], text })),
    correctId: LETTERS[correct],
    explanation,
  };
}

